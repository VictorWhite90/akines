import { MagicStar, ShieldTick, UserTick } from "iconsax-reactjs";
import type { TrustSource } from "@/lib/types";
import { cn } from "@/lib/cn";

const LABELS: Record<TrustSource, { text: string; title: string; className: string; Icon: typeof ShieldTick }> = {
  verified: {
    text: "Verified",
    title: "Checked by Artelia against documents or records.",
    className: "bg-verified-bg text-verified",
    Icon: ShieldTick,
  },
  "self-declared": {
    text: "Self-declared",
    title: "Stated by the member. Not independently checked.",
    className: "bg-declared-bg text-declared",
    Icon: UserTick,
  },
  ai: {
    text: "AI suggestion",
    title: "Generated by Artelia's matching model. You can edit, dismiss or ask why.",
    className: "bg-ai-bg text-ai",
    Icon: MagicStar,
  },
};

/**
 * Marks where a piece of information comes from. The concept note requires a
 * clear distinction between verified facts, self-declared information and AI
 * recommendations — use this wherever any of the three is shown.
 */
export default function TrustLabel({
  source,
  compact = false,
  className,
}: {
  source: TrustSource;
  compact?: boolean;
  className?: string;
}) {
  const { text, title, className: tone, Icon } = LABELS[source];
  return (
    <span
      title={title}
      className={cn(
        "inline-flex items-center gap-1 rounded-full font-semibold leading-none",
        compact ? "px-1.5 py-1 text-[10px]" : "px-2.5 py-1 text-[11px]",
        tone,
        className,
      )}
    >
      <Icon size={compact ? 11 : 13} variant="Bold" color="currentColor" aria-hidden />
      {compact ? <span className="sr-only">{text}</span> : text}
      {compact && <span aria-hidden>{text.split(" ")[0]}</span>}
    </span>
  );
}
